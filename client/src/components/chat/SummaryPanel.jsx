import { useState, useEffect } from "react";
import api from "../../api/client";
import SidePanel from "../ui/SidePanel";
import { X, Sparkles, RefreshCw } from "lucide-react";

export default function SummaryPanel({ chatId, onClose }) {
  const [summary, setSummary] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  const fetchSummary = async () => {
    setLoading(true); setError(null);
    try {
      const data = await api.get(`/ai/chats/${chatId}/summary`);
      setSummary(data.data.summary);
    } catch (err) { setError(err?.message || "Failed to generate summary"); }
    setLoading(false);
  };

  useEffect(() => { fetchSummary(); }, [chatId]);

  return (
    <SidePanel onClose={onClose}>
      <div style={{ padding: "16px 20px", borderBottom: "1px solid var(--border)", display: "flex", alignItems: "center", justifyContent: "space-between", flexShrink: 0 }}>
        <h3 style={{ fontSize: 15, fontWeight: 600, display: "flex", alignItems: "center", gap: 8 }}>
          <Sparkles size={16} style={{ color: "var(--accent)" }} /> AI Summary
        </h3>
        <div style={{ display: "flex", gap: 2 }}>
          <button className="icon-btn" onClick={fetchSummary} title="Regenerate" disabled={loading}>
            <RefreshCw size={16} style={{ animation: loading ? "spin 1s linear infinite" : "none" }} />
          </button>
          <button className="icon-btn" onClick={onClose}><X size={18} /></button>
        </div>
      </div>
      <div style={{ flex: 1, overflowY: "auto", padding: 20 }}>
        {loading ? (
          <div style={{ textAlign: "center", padding: "40px 0", color: "var(--text-tertiary)" }}>
            <div style={{ marginBottom: 16 }}><Sparkles size={24} style={{ color: "var(--accent)", animation: "pulse 2s infinite" }} /></div>
            <div style={{ display: "flex", justifyContent: "center", marginBottom: 12 }}><div className="spinner spinner-md" /></div>
            <div style={{ fontSize: 13 }}>Analyzing conversation...</div>
          </div>
        ) : error ? (
          <div style={{ padding: 16, background: "var(--red-soft)", border: "1px solid var(--red)", borderRadius: "var(--radius-md)", fontSize: 13, color: "var(--red)" }}>{error}</div>
        ) : (
          <>
            <div style={{ background: "var(--bg-tertiary)", border: "1px solid var(--border)", borderRadius: "var(--radius-md)", padding: 16, fontSize: 13, lineHeight: 1.7, color: "var(--text-secondary)", whiteSpace: "pre-wrap" }}>{summary}</div>
            <div style={{ marginTop: 12, fontSize: 11, color: "var(--text-tertiary)", textAlign: "center", fontStyle: "italic" }}>Generated by AI — may not capture all nuances</div>
          </>
        )}
      </div>
      <style>{`
        @keyframes spin { to { transform: rotate(360deg) } }
        @keyframes pulse { 0%,100% { opacity:1 } 50% { opacity:0.4 } }
      `}</style>
    </SidePanel>
  );
}
